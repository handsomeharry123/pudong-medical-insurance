import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>sessionStorage.setItem('pudong-auth-user','user-000'));
await page.goto('http://localhost:3001/app/home/overview');
await page.locator('.reg-module-card').filter({hasText:'医保数据分析'}).click();
await page.locator('.reg-module-card').filter({hasText:'医疗机构监管履历画像'}).click();
await page.getByRole('button',{name:'监管履历查询',exact:true}).click();
await page.getByText('您好！我是医小保。',{exact:false}).first().waitFor();
await page.getByRole('button',{name:'查询全区风险最高的5条监管记录。',exact:true}).click();
await page.getByText('共 5 次',{exact:true}).waitFor();
await page.getByRole('button',{name:'检查详情',exact:true}).first().click();
await page.getByRole('button',{name:'查看风险指标明细',exact:true}).last().waitFor();
await page.getByRole('button',{name:'查看风险指标明细',exact:true}).last().click();
const downloadButton=page.getByRole('button',{name:'下载当前筛选指标 Excel'}).last();await downloadButton.waitFor();
const [download]=await Promise.all([page.waitForEvent('download'),downloadButton.click()]);
await download.saveAs('/tmp/history-indicators.xlsx');
await page.screenshot({path:'/tmp/history-flow.png',fullPage:true});
assert.deepEqual(errors,[]);console.log('页面入口、全区前5条、选择批次、指标穿透及Excel下载通过');
await browser.close();
